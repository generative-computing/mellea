"""Check that links in the example documentation point at real files."""

from __future__ import annotations

import re
from collections.abc import Iterator
from pathlib import Path
from urllib.parse import unquote, urlsplit

REPOSITORY_ROOT = Path(__file__).parents[1]
EXAMPLES_ROOT = REPOSITORY_ROOT / "docs" / "examples"

# The CLI page is generated during the documentation build and intentionally is not
# checked into the repository.
GENERATED_DOCS = {REPOSITORY_ROOT / "docs" / "docs" / "reference" / "cli.md"}
LINK_RE = re.compile(r"!?\[[^\]]*\]\(\s*(?:<([^>]+)>|([^\s)]+))")


def _without_inline_code(line: str) -> str:
    """Remove spans bounded by matching, complete backtick runs."""
    runs = list(re.finditer(r"`+", line))
    visible = []
    cursor = index = 0
    while index < len(runs):
        opening = runs[index]
        start = opening.start()
        prefix = line[:start]
        backslashes = len(prefix) - len(prefix.rstrip("\\"))
        start += backslashes % 2  # An escaped first backtick is literal text.
        width = opening.end() - start
        closing = next(
            (i for i in range(index + 1, len(runs)) if len(runs[i][0]) == width), None
        )
        if not width or closing is None:
            index += 1
            continue
        visible.append(line[cursor:start])
        cursor = runs[closing].end()
        index = closing + 1
    return "".join(visible) + line[cursor:]


def _local_links(path: Path) -> Iterator[str]:
    fence = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if fence:
            if re.fullmatch(
                rf" {{0,3}}{re.escape(fence[0])}{{{len(fence)},}}[ \t]*", line
            ):
                fence = ""
            continue
        if match := re.match(r" {0,3}(`{3,}|~{3,})", line):
            fence = match[1]
            continue
        line = _without_inline_code(line)
        yield from (first or second for first, second in LINK_RE.findall(line))


def _missing_links(
    examples_root: Path = EXAMPLES_ROOT, repository_root: Path = REPOSITORY_ROOT
) -> list[str]:
    missing = []
    for markdown_file in examples_root.rglob("*.md"):
        for target in _local_links(markdown_file):
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc:
                continue
            target_path = (markdown_file.parent / unquote(parsed.path)).resolve()
            if target_path.exists() or target_path in GENERATED_DOCS:
                continue
            missing.append(f"{markdown_file.relative_to(repository_root)}: {target}")
    return missing


def test_example_markdown_links_resolve():
    """Prevent broken relative links from being added outside Docusaurus."""
    assert not (missing := _missing_links()), "Broken example links:\n" + "\n".join(
        missing
    )


def test_missing_example_link_is_reported(tmp_path: Path) -> None:
    """Demonstrate that the check fails for a broken relative target."""
    (tmp_path / "README.md").write_text("[Broken](missing.md)", encoding="utf-8")
    assert _missing_links(tmp_path, tmp_path) == ["README.md: missing.md"]


def test_valid_example_links_resolve(tmp_path: Path) -> None:
    """Accept anchors, encoded filenames, and external links."""
    (tmp_path / "my file.md").write_text("# Section", encoding="utf-8")
    (tmp_path / "README.md").write_text(
        "[Valid](my%20file.md#section)\n"
        "[Anchor](#section)\n"
        "[External](https://example.com/missing.md)\n",
        encoding="utf-8",
    )
    assert _missing_links(tmp_path, tmp_path) == []


def test_example_links_in_code_are_ignored(tmp_path: Path) -> None:
    """Ignore inline code and both fence styles without hiding real links."""
    (tmp_path / "README.md").write_text(
        "`[Inline](missing.md)` and `` `[Nested](missing.md)` ``\n"
        "\\\\`[Escaped slash](missing.md)` and \\``[Escaped tick](missing.md)`\n"
        "```markdown\n[Backticks](missing.md)\n```\n"
        "~~~markdown\n[Tildes](missing.md)\n~~~\n"
        "````markdown\n```\n[Long fence](missing.md)\n````\n"
        "[Real](real-missing.md)\n",
        encoding="utf-8",
    )
    assert _missing_links(tmp_path, tmp_path) == ["README.md: real-missing.md"]


def test_generated_cli_reference_is_allowed(tmp_path: Path) -> None:
    """Preserve the exception for the CLI page generated by the docs build."""
    import os

    target = next(iter(GENERATED_DOCS))
    relative = os.path.relpath(target, tmp_path)
    (tmp_path / "README.md").write_text(f"[CLI]({relative})", encoding="utf-8")
    assert _missing_links(tmp_path, tmp_path) == []


def test_mismatched_inline_code_does_not_hide_links(tmp_path: Path) -> None:
    """Keep links active when the backtick runs do not form a code span."""
    (tmp_path / "README.md").write_text(
        "`prefix [Broken](missing.md) ``\n"
        "``prefix [Other](other.md) ```\n"
        "\\`prefix [Escaped](escaped.md) `\n",
        encoding="utf-8",
    )
    assert _missing_links(tmp_path, tmp_path) == [
        "README.md: missing.md",
        "README.md: other.md",
        "README.md: escaped.md",
    ]
